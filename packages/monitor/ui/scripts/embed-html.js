import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const distHtmlPath = path.resolve(__dirname, '../dist/index.html');
const targetTsPath = path.resolve(__dirname, '../../src/ui/dashboard.ts');

if (!fs.existsSync(distHtmlPath)) {
  console.error('Dist HTML not found at:', distHtmlPath);
  process.exit(1);
}

const rawHtml = fs.readFileSync(distHtmlPath, 'utf8');

// Escape backslashes, backticks and string interpolations for template string safety
const escapedHtml = rawHtml
  .replace(/\\/g, '\\\\')
  .replace(/`/g, '\\`')
  .replace(/\${/g, '\\${');

const tsContent = `// Auto-generated by @siglo/monitor-ui Vite build. Do not edit directly.
export function getDashboardHtml(): string {
    return \`${escapedHtml}\`;
}
`;

fs.writeFileSync(targetTsPath, tsContent, 'utf8');
console.log('Successfully embedded Vite single-file HTML into:', targetTsPath);
